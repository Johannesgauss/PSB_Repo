.nolist
.include "m328Pdef.inc"
.list

.ORG 0x000

Tabela: 
    .db 0b00111111, 0b00000110 
    .db 0b01011011, 0b01001111 
    .db 0b01100110, 0b01101101 

.def AUX = R16
.def I   = R17
.def J   = R18
.def VAL = R19

.equ BUTTON_A = PD7
.equ BUTTON_B = PD6

INIT:
    LDI AUX, HIGH(RAMEND)
    OUT SPH, AUX
    LDI AUX, LOW(RAMEND)
    OUT SPL, AUX

    STS UCSR0B, R1


    LDI AUX, 0b01111111
    OUT DDRB, AUX
    

    LDI AUX, 0b00000000
    OUT DDRD, AUX

    LDI AUX, 0b11000000
    OUT PORTD, AUX

  
    LDI J, 0
    LDI I, 0

    RCALL SHOW

OBSERVATOR:
   
    SBIS PIND, BUTTON_A
    RJMP INCREASING_MODE

  
    SBIS PIND, BUTTON_B
    RJMP DECREASING_MODE

    RJMP OBSERVATOR

INCREASING_MODE:
    RCALL DELAY

WAIT_RELEASE_A:
    SBIS PIND, BUTTON_A
    RJMP WAIT_RELEASE_A

    RCALL NEXT_ELEMENT
    RCALL SHOW
    RJMP OBSERVATOR

DECREASING_MODE:
    RCALL DELAY

WAIT_RELEASE_B:
    SBIS PIND, BUTTON_B
    RJMP WAIT_RELEASE_B

    RCALL PREV_ELEMENT
    RCALL SHOW
    RJMP OBSERVATOR

NEXT_ELEMENT:
    INC I
    CPI I, 2
    BRNE DONE_NEXT
    LDI I, 0
    INC J
    CPI J, 3
    BRNE DONE_NEXT
    LDI J, 0
DONE_NEXT:
    RET

PREV_ELEMENT:
    DEC I
    BRPL DONE_PREV
    LDI I, 1
    DEC J
    BRPL DONE_PREV
    LDI J, 2
DONE_PREV:
    RET

SHOW:
    MOV AUX, J
    ;LSL AUX
    LDI R25, 2
    MUL R25, AUX
    MOV AUX, R0
    ADD AUX, I

    LDI ZH, HIGH(Tabela << 1)
    LDI ZL, LOW(Tabela << 1)


    ADD ZL, AUX
    CLR AUX
    ADC ZH, AUX


    LPM VAL, Z
    

    OUT PORTB, VAL
    RET

DELAY:
    LDI R22, 50
L3: LDI R20, 255
L2: LDI R21, 255
L1: DEC R21
    BRNE L1
    DEC R20
    BRNE L2
    DEC R22
    BRNE L3
    RET
