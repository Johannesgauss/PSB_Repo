.nolist
.include "../m328Pdef.inc"


.ORG 0x000
;            xgfedcba
.equ n0  = 0b00111111
.equ n1  = 0b00000110
.equ n2  = 0b01011011
.equ n3  = 0b01001111
.equ n4  = 0b01100110
.equ n5  = 0b01101101
.equ n6  = 0b01111101
.equ n7  = 0b00000000
.equ n8  = 0b00000000
.equ n9  = 0b00000000
.equ n10 = 0b00000000
.equ n11 = 0b00000000
.equ n12 = 0b00000000
.equ n13 = 0b00000000
.equ n14 = 0b00000000
.equ n15 = 0b00000000

.def AUX = R16
.def AUXB = R17
.equ BUTTON_A = PD7 ; for increasing
.equ BUTTON_B = PD6 ; for decreasing

INIT:
	LDI AUX, HIGH(RAMEND)
	OUT SPH, AUX

	LDI AUX, LOW(RAMEND)
	OUT SPL, AUX

	LDI AUX, 0b01111111
	OUT DDRB, AUX
	LDI AUX, 0b11000000
	OUT DDRD, AUX
	LDI AUX, 0b00000000
	OUT PORTB, AUX
	;NOP

OBSERVATOR:
	SBIC PIND, BUTTON_A
	RJMP INCREASING_MODE
	SBIC PIND, BUTTON_B
	RJMP DECREASING_MODE
	RJMP OBSERVATOR

INCREASING_MODE:
	SBIC PIND, BUTTON_A
	RJMP INCREASING_MODE
INCREASING:
	RCALL SHOW
	RCALL DELAY
	INC AUX
	SBIS PIND, BUTTON_B
	RJMP INCREASING
	RJMP DECREASING
DECREASING_MODE:
	SBIC PIND, BUTTON_B
	RJMP DECREASING
DECREASING:
	RCALL SHOW
	RCALL DELAY
	DEC AUX
	SBIS PIND, BUTTON_A
	RJMP DECREASING
	RJMP INCREASING
SHOW:
	MOV AUXB, AUX
	CPI AUXB, 0x00
	BRNE test_n1
	LDI AUXB, n0
	OUT PORTB, AUXB
	RET
test_n1:
	CPI AUXB, 0x01
	BRNE test_n2
	LDI AUXB, n1
	OUT PORTB, AUXB
	RET
test_n2:
	CPI AUXB, 0x02
	BRNE test_n3
	LDI AUXB, n2
	OUT PORTB, AUXB
	RET
test_n3:
	CPI AUXB, 0x03
	BRNE test_n4
	LDI AUXB, n3
	OUT PORTB, AUXB
	RET
test_n4:
	CPI AUXB, 0x04
	BRNE test_n5
	LDI AUXB, n4
	OUT PORTB, AUXB
	RET
test_n5:
	CPI AUXB, 5
	BRNE test_n6
	LDI AUXB, n5
	OUT PORTB, AUXB
	RET
test_n6:
	CPI AUXB, 6
	BRNE test_n7
	LDI AUXB, n6
	OUT PORTB, AUXB
	RET
test_n7:
	CPI AUXB, 7
	BRNE test_n8
	LDI AUXB, n7
	OUT PORTB, AUXB
	RET
test_n8:
	CPI AUXB, 8
	BRNE test_n9
	LDI AUXB, n8
	OUT PORTB, AUXB
	RET
test_n9:
	CPI AUXB, 9
	BRNE test_n10
	LDI AUXB, n9
	OUT PORTB, AUXB
	RET
test_n10:
	CPI AUXB, 10
	BRNE test_n11
	LDI AUXB, n10
	OUT PORTB, AUXB
	RET
test_n11:
	CPI AUXB, 11
	BRNE test_n12
	LDI AUXB, n11
	OUT PORTB, AUXB
	RET
test_n12:
	CPI AUXB, 12
	BRNE test_n13
	LDI AUXB, n12
	OUT PORTB, AUXB
	RET
test_n13:
	CPI AUXB, 13
	BRNE test_n14
	LDI AUXB, n13
	OUT PORTB, AUXB
	RET
test_n14:
	CPI AUXB, 14
	BRNE test_n15
	LDI AUXB, n14
	OUT PORTB, AUXB
	RET
test_n15:
	LDI AUXB, 15
	OUT PORTB, AUXB
	RET
DELAY:
    LDI R20, 50
L3: LDI R17, 255
L2: LDI R18, 255
L1: DEC R18
    BRNE L1
    DEC R17
    BRNE L2
    DEC R20
    BRNE L3
    RET
