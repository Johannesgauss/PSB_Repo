.nolist
.include "../../m328Pdef.inc"

.ORG 0x000

.def AUX = R16
.def BUX = R17
.equ BUTTON_A = PD7 ; for increasing
.equ BUTTON_B = PD6 ; for decreasing

INIT:
	LDI AUX, 0xFF
	OUT DDRB, AUX
	LDI AUX, 0b00000011
	OUT DDRD, AUX
	LDI AUX, 0b00000000
	OUT PORTB, AUX

	LDI AUX, LOW(RAMEND)
	OUT SPL, AUX

	LDI AUX, HIGH(RAMEND)
	OUT SPH, AUX
MAIN:
	SBIC PIND, BUTTON_A		
	RJMP MAIN
BOUNCE:
	SBIS PIND, BUTTON_A
	RJMP BOUNCE
	LDI AUX, 0xFF
	ANDI AUX, 0b00000001
	OUT PORTB, AUX
	RJMP DELAY
DELAY:
    LDI R20, 50
L3: LDI R18, 255
L2: LDI R19, 255
L1: DEC R19
    BRNE L1
    DEC R18
    BRNE L2
    DEC R20
    BRNE L3
    RET
