.nolist
.include "../../m328Pdef.inc"

.ORG 0x000
             ; xfedcba
Tabela: .db 0b0000001, 0b0000011, 0b0000111, 0b0001111, 0b0011111, 0b0111111

.def AUX = R16
.equ BUTTON_A = PD7 ; for increasing
.equ BUTTON_B = PD6 ; for decreasing

INIT:
	LDI AUX, 0xFF
	OUT DDRB, AUX
	LDI AUX, 0b00000000
	OUT PORTB, AUX

	LDI AUX, LOW(RAMEND)
	OUT SPL, AUX

	LDI AUX, HIGH(RAMEND)
	OUT SPH, AUX
POINTER_INIT:
	LDI ZL, LOW(Tabela<<1)
	LDI ZH, HIGH(Tabela<<1)
MAIN:
	LPM AUX, Z
	OUT PORTB, AUX
	INC ZL
	RCALL DELAY
	RJMP MAIN
		
DELAY:
    LDI R20, 50
L3: LDI R17, 255
L2: LDI R18, 255
L1: DEC R18
    BRNE L1
    DEC R17
    BRNE L2
    DEC R20
    BRNE L3
    RET
